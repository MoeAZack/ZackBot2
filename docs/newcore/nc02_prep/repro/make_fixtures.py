def contract_sha(fx):
    c = {k: fx[k] for k in ('id', 'reader_build', 'input_files', 'exchange', 'nc02_required')}
    return hashlib.sha256(json.dumps(c, sort_keys=True, separators=(',', ':')).encode()).hexdigest()


