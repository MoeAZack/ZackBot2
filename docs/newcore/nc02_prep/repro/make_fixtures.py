def stamp(name, v):
    return lambda t: C.rewrite(os.path.join(t, name), lambda d: d.update(schema_version=v))


def trunc(name):
    def f(t):
        p = os.path.join(t, name)
        with open(p, 'rb') as fh: raw = fh.read()
        with open(p, 'wb') as fh: fh.write(raw[:40])
    return f


def badlot(name):
    def m(d): d['lots'][next(iter(d['lots']))]['qty'] = 'abc'
    return lambda t: C.rewrite(os.path.join(t, name), m)


def rm(*names):
    def f(t):
        for n in names:
            if os.path.exists(os.path.join(t, n)): os.remove(os.path.join(t, n))
    return f


def seq(*fs):
    return lambda t: [f(t) for f in fs]


